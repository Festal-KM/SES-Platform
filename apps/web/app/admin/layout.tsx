import type { ReactNode } from 'react';
import { t } from '@ses/i18n';

/**
 * 🔴 **平面帯（`docs/04` §3.3 の区別手段 #1）。** 「いまどちらの平面にいるか」を一目で
 *    判別できないと、運営者は read-only の前提を忘れて操作しようとする（代理閲覧・停止操作の
 *    誤爆）。Phase 2 の `F-060`（代理閲覧）はこの区別の上に乗る。
 *
 * 🔴 **`docs/04` は「色でなく『帯という構造の有無』で区別する」と定めている**（色覚特性に
 *    依存しないため）。したがって守るべきは**全幅のブロックが最上部に常時在ること**であり、
 *    色はその補助である。**折りたたみ・条件付き表示・装飾扱いの縮小をしない。**
 *
 * T-21-03 で手書き CSS（`.ses-plane-band`）から Tailwind のユーティリティへ移した。
 *
 * ============================================================================
 * 🔴 SP-22 段⑤（`T-22-14`）: **帯を濃色でなくした**（見え方が変わる 1 件）
 * ============================================================================
 * 旧実装は `bg-slate-800` / `text-slate-50` の**濃紺の帯**だった。段⑤ でこれを
 * 無彩色の淡い帯（`bg-bg-inset` + 下罫 + `text-fg`）に替えた。**理由は 3 つあり、
 * どれも「落ちたから直した」ではない。**
 *
 *   ① 🔴 **`docs/04` §7.9 は「濃色の面はサイドバー 1 部品だけ」と定めている**
 *      （`--color-sidebar-*` の 8 色は `packages/ui/src/components/sidebar.tsx` の外では
 *      使えず、機械検査が落とす）。帯は面であり、2 つ目の濃色の面を増やすには §7.9 の
 *      改訂（= 人間の判断）が要る。**代わりに primitive（`slate-800`）を直書きするのは
 *      「トークンの外に色を置く」ことであり、§7.9 の 3 層が崩れる入口そのものである。**
 *   ② 🔴 **`docs/04` §3.3-1 は「色でなく『帯という構造の有無』で区別する」と定めている**
 *      （色覚特性に依存しないため）。したがって守るべきは**全幅のブロックが最上部に常時
 *      在ること**であり、濃さではない。**ここは 1 文字も変えていない。**
 *   ③ 🔴 **改訂 24 で平面の区別は「①第 2 階層の帯の有無 ②濃色の縦の柱の有無」になった。**
 *      主平面には濃色のサイドバーが必ず在り、管理平面には無い —— **柱の有無が平面の差を
 *      運んでいる**ので、帯の濃さを下げても判別手段は 2 つとも残る。
 *      🔴 **帯に意味の色（青 = `info` 等）を当てない**（`docs/04` §3.3 の 🔴。色を平面の差に
 *      すると、状態色の意味が平面ごとに違うという最悪の読み違いの入口になる）。だから無彩色である。
 *
 * 旧宣言との対応（寸法・字詰め・配置は 1 つも変えていない）:
 *
 *   `background:#1e293b`      → ~~`bg-slate-800`~~ → **`bg-bg-inset`**（`slate-100`）+ `border-b border-border`
 *   `color:#f8fafc`           → ~~`text-slate-50`~~ → **`text-fg`**（`slate-900`）
 *   `font-size:0.8125rem`     → ~~`text-[0.8125rem]`~~ → **`text-cell`**（§7.9 の 13px。**実寸は同じ**）
 *   `font-weight:700`         → `font-bold`（`--font-weight-bold: 700`）
 *   `letter-spacing:0.08em`   → `tracking-[0.08em]`（🔴 字詰めは §7.9 の段を持たない値であり、
 *                               帯の「見出しらしさ」を担っているのでそのまま残す）
 *   `padding:0.5rem 1rem`     → `py-2 px-4`（`--spacing: .25rem`）
 *   `text-align:center`       → `text-center`
 */
const PLANE_BAND_CLASS =
  'border-b border-border bg-bg-inset px-4 py-2 text-center text-cell font-bold tracking-[0.08em] text-fg';

export default function AdminLayout({ children }: { children: ReactNode }) {
  return (
    // 🔴 外側の `div` はスタイルを持たない（旧 `.ses-admin-plane` にも CSS 規則は無かった）。
    //    「平面帯 + 中身」を 1 つの平面としてまとめる入れ物であり、**DOM を変えないために
    //    残している**（`docs/sprints/SP-21` §5「要素の並びを変えない」）。ここに背景色や
    //    高さを足すと、それは T-21-05（管理平面 3 画面）の判断を先取りすることになる。
    <div>
      <p className={PLANE_BAND_CLASS}>{t('admin.plane.band')}</p>
      {children}
    </div>
  );
}
