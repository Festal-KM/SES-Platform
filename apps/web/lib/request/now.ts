// apps/web/lib/request/now.ts
// 🔴 **1 リクエスト内で 1 つの「いま」**（T-12-20 の code-reviewer 指摘 #5）。
//
// ============================================================================
// なぜ要るのか
// ============================================================================
// 共通外枠（`app/(main)/layout.tsx`）とページは**同じリクエストの中で同じ読み取りを要求する**
// ことがある（`/settings/usage` は、ヘッダの上限インジケータと `S-038` 本体がどちらも
// `readUsageView` を読む）。React の `cache()` は**引数の同一性**でヒットを判定するため、
// 両者が別々に `new Date()` を作ると、ctx が同一でもキャッシュが当たらず DB を 2 度読む。
// そこで「いま」自体をリクエスト内で 1 つに固定する。
//
// 副次的だが重要な効果: **同一リクエスト内の判定が同じ時刻で行われる。** 外枠が「上限に接近」を
// 出しているのに本文が別の時刻で判定して違う水準を出す、という食い違いが構造的に起きない
// （`lib/shell/usage-indicator.ts` の「決定的であること自体が要件である」）。
//
// 🔴 `cache()` の有効範囲は**そのリクエストのレンダリング**だけであり、リクエストを越えて
//    共有されない。したがって「時刻が固まったまま次のリクエストでも使われる」ことは無い。
//    モジュールスコープの変数に Date を持たせる実装に置き換えてはならない
//    （`apps/web/lib/auth/request-cache.test.ts` が同じ不変条件を固定する）。
// 🔴 ジョブ・API ハンドラはこれを使わない。あちらは `now` を引数で受け取る設計であり
//    （`packages/domain` は現在時刻を自分で取らない。`CLAUDE.md` §2.1）、本関数は
//    **画面のレンダリングという 1 リクエスト = 1 描画の単位**でだけ意味を持つ。
import { cache } from 'react';

/** そのリクエストの「いま」。同一リクエスト内では常に同じ `Date` インスタンスを返す。 */
export const requestNow = cache((): Date => new Date());
