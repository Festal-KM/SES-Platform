// 直し方: 🔴 **ハイライトを当てる最小の部分だけをクライアント部品にした**
//       （`app/(main)/_shell/nav-current.tsx` の 2 つの島。`usePathname()` を読むのはそこだけで、
//       `AppShell` / `layout.tsx` / 各画面に `'use client'` は 1 つも付いていない）。
// 🔴 **この関数の値は捨てていない。** 島が上書きするのは水和後であり、ここで返す値は
//    **初回描画（水和前 / JS が効かない環境）の現在地**として現に効いている。
//
// 🔴 **これは認可の材料ではない。** 表示（現在地のハイライト）だけに使う値であり、**信頼していない**
//    （ヘッダは `proxy.ts` が毎リクエストで上書きするので外部から差し込めないが、仮に任意の値が
//    入っても起きることは「サイドバーの 1 項目が選択状態に見える」だけである）。
//    境界の強制は各画面 / 各 API の `resolveTenantCtxOutcome` + `withTenant` が行う。
//
// 🔴 **ヘッダ名はこのファイルに置かない。** `proxy.ts`（Edge）が同じ定数を要るが、この
//    ファイルは `next/headers` を import しており Edge から読めない。定数だけを
//    `./current-path-header.ts`（import を 1 本も持たない）に切り出し、**両者がそこから読む**
//    （理由は同ファイル冒頭。`lib/auth/cookie-names.ts` と同型の切り分けである）。
import { headers } from 'next/headers';
import { CURRENT_PATH_HEADER } from './current-path-header';

/**
 * いま開いている画面のパス（`/engineers/123` など）。
 *
 * 🔴 **取れなかったときは空文字を返す**（`/` ではない）。`/` を返すと、ヘッダが欠けた経路で
 *    **ホームが現在地として光る** —— 現在地の誤表示は「押した覚えのない場所に居る」ことになり、
 *    何も光らないより悪い。`isCurrentNavPath('', href)` はどの項目にも一致しない。
 */
export async function readCurrentPath(): Promise<string> {
  const headerList = await headers();
  return headerList.get(CURRENT_PATH_HEADER) ?? '';
}
