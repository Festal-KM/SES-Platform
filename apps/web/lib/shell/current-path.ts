// ところが **React Server Components のレイアウトは自分のパスを受け取らない**（`params` しか無い）。
//
//   | 案 | なぜ採らないか |
//   |---|---|
//   | `usePathname()` を使う | 🔴 クライアント専用。外枠に `'use client'` が付くと、**包まれる主平面の全画面**がクライアントバンドルへ移る（`tests/static/client-db-boundary.test.ts` の前提が崩れる。`T-22-05` 受け入れ基準 5） |
//   | 各セクションに `layout.tsx` を足して `current` を渡す（管理平面の作法） | 主平面には現在セクション別レイアウトが無く、**10 枚のレイアウトを新設する ＝ ルート木を変える**ことになる（`SP-22` §3.1-3「URL / ルーティング / 境界の位置を変えない」） |
//   | 🔴 **`proxy.ts` がリクエストヘッダにパスを添え、レイアウトが読む** | **追加のみ**で済む（リダイレクトの判定・Cookie の扱い・`matcher` を 1 行も変えない）。Next.js が公式に用意している唯一の「ミドルウェア → サーバコンポーネント」の受け渡しである |
//
// 🔴 **これは認可の材料ではない。** 表示（現在地のハイライト）だけに使う値であり、**信頼していない**
//    （ヘッダは `proxy.ts` が毎リクエストで上書きするので外部から差し込めないが、仮に任意の値が
//    入っても起きることは「サイドバーの 1 項目が選択状態に見える」だけである）。
//    境界の強制は各画面 / 各 API の `resolveTenantCtxOutcome` + `withTenant` が行う。
import { headers } from 'next/headers';

/** 🔴 `apps/web/proxy.ts` が添える名前。**両者でこの定数を共有する**（綴りを 2 箇所に書かない）。 */
export const CURRENT_PATH_HEADER = 'x-ses-pathname';

/**
 * いま開いている画面のパス（`/engineers/123` など）。
 *
 * 🔴 **取れなかったときは空文字を返す**（`/` ではない）。`/` を返すと、ヘッダが欠けた経路で
 *    **ホームが現在地として光る** —— 現在地の誤表示は「押した覚えのない場所に居る」ことになり、
 *    何も光らないより悪い。`isCurrentNavPath('', href)` はどの項目にも一致しない。
 */
export async function readCurrentPath(): Promise<string> {
  const headerList = await headers();
  return headerList.get(CURRENT_PATH_HEADER) ?? '';
}
