-- T-05-01（docs/sprints/SP-05-engineer-ledger.md）: エンジニア台帳の登録・編集（`F-008` / `S-007`）が
-- グローバルなスキル辞書（`skills`）を**読む**ために必要な最小の GRANT。
-- 一次資料: docs/05 §4.2（DB ロールと接続）/ §4.4「射程外の 4 表」/ `F-010 AC-2` / `BR-02`。
--
-- 🔴 なぜ必要か: `skills` は `CLAUDE.md` §3.1 の射程外 4 表であり RLS を持たない。RLS が無い＝
--    誰でも読めるではなく、**GRANT が無ければ `permission denied`** である。20260903050000 の §13 は
--    52 表を列挙して `app_tenant` に GRANT したが、射程外の 4 表は 1 つも含んでいない。
--    そのため `withTenant` から `db.skill.findMany()` を呼ぶと権限エラーになる。
--    `F-008` 処理②「スキルは `F-010` の辞書から選ぶ」を成立させるには読み取りが要る。
--
-- 🔴 **`SELECT` だけを与える。** `INSERT` / `UPDATE` / `DELETE` を与えない ——
--    「グローバル辞書（`Skill`）はテナントから編集できない」（`F-010 AC-2` / `BR-02` の射程）を
--    アプリの `if` ではなく **DB 権限**で担保する。テナント固有の別名（`skill_aliases`）は
--    既に GRANT 済みであり、そちらが「テナントが増やしてよい表」である。
--
-- 🔴 `app_platform`（運営者）には与えない。運営者に必要なのは件数・状態・エラーであって
--    辞書の内容ではない（`CLAUDE.md` §10.5）。必要になった時点で §5.5 の列レベル GRANT として足す。
GRANT SELECT ON skills TO app_tenant;
