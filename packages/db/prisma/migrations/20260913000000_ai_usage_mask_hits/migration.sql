-- ============================================================================
-- 🔴 `ai_usage.mask_pattern_hits` —— 「パターン検出による追加マスキング」の記録先
-- ============================================================================
-- docs/03 §4.2 は、マスキングの ②パターン検出（補助）について「検出したら置換したうえで
-- **`AiUsage` に記録する**」と定める。T-07-02 は `mask()` が要約（種別・方式・件数）を返す
-- ところまでを実装し、記録先の用意を T-07-03 へ申し送った（docs/05 §7.10 ⑤）。その受け皿である。
--
-- 🔴 **なぜ記録するのか**: 補助（正規表現）が拾ったということは、**台帳（`Engineer` の氏名・
--    連絡先・現所属会社名）に無い個人情報が本文に混じっていた**ということである。主たる担保は
--    ①既知値の置換であり、②が働いた回数は「①の母集団が欠けている」兆候そのものになる。
--    ここを残さないと、`CLAUDE.md` §7 の「PII 未マスキングでの LLM 送信 0 件」が
--    「たまたま正規表現が拾っていただけ」で維持されている状態に気づけない。
--
-- 🔴 **一致した文字列は入らない**（docs/05 §7.10 ⑤）。入るのは `{"EMAIL": 2, "PHONE": 1}` の形、
--    すなわち**種別ごとの件数だけ**である。原文を入れると、マスキングの記録それ自体が
--    PII の再出現経路になる（監査ログに PII を入れない規律と同じ。docs/05 §16.2）。
--
-- 🔴 **`KNOWN_VALUE`（台帳の値による置換）は入れない。** あちらは起きて当然の主経路であり、
--    混ぜると上記の兆候が主経路の件数に埋もれる。
--
-- 🔴 **NOT NULL + 既定 `{}`** にする。NULL を許すと「検出が無かった」と「記録し忘れた」が
--    区別できなくなり、欠測の検知（`F-026 AC-4`）が成立しない。既存行（記録機構より前に
--    書かれた行は存在しないが、順序として）にも `{}` が入る。
ALTER TABLE "ai_usage"
  ADD COLUMN IF NOT EXISTS "mask_pattern_hits" JSONB NOT NULL DEFAULT '{}'::jsonb;

COMMENT ON COLUMN "ai_usage"."mask_pattern_hits" IS
  'パターン検出（補助）による追加マスキングの要約 {種別: 件数}。一致した文字列は入れない（docs/03 §4.2 / docs/05 §7.10 ⑤。T-07-03）。この試行に渡した入力を説明する値であり、再試行の行は同じ入力を説明するため同じ値を持つ（出現回数を数えるときは attempt_no = 1 で絞る）';

