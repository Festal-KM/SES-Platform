--    `apps/web/lib/settings/account.ts` の 🔴 と、その単体テストが固定する）。
--
-- 🔴 **`null` 許容である。** 既存の利用者には役職が無く、既定値を入れると「本当は空なのに
--    何か入っている」状態を作る（`disabled_at` と同じ扱い）。画面は `null` を「未設定」と出す。
--
-- 🔴 **CHECK を置かない。** 自由入力であり、長さの上限は Zod（`ACCOUNT_JOB_TITLE_MAX_LENGTH`）が
--    持つ（`display_name` と同じ扱い。`tests/static/schema-enum-drift.test.ts` の対象でもない）。
--
-- 🔴 **GRANT を足す必要が無い。** `users` は列レベルではなく表レベルで
--    `GRANT SELECT, INSERT, UPDATE ... TO app_tenant` されており（migration 20260903050000）、
--    PostgreSQL の表レベル GRANT は**後から足した列にも及ぶ**（`tenants` のように列を列挙して
--    いる表なら GRANT の追加が要る —— ここは列挙していない）。
--
-- 🔴 **運営者（`app_platform`）には見せない。** `users` への `SELECT` は元から与えていない
--    （`CLAUDE.md` §10.5「運営者にも見せないもの: エンジニアの氏名・連絡先…」と同じ理由で、
--    利用者の属性も運営には要らない。要るのは件数・状態・エラーである）。

