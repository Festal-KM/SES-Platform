// packages/db/src/search/free-word.ts
// 🔴 **フリーワード（自由文）検索の唯一の実装点**（SP-06 T-06-05 / docs/05 TBD-8 / docs/03 §3.7）。
//
// ============================================================================
// なぜ 1 箇所に閉じるのか
// ============================================================================
// `docs/03` §3.7.3 は、性能目標（`F-009 AC-4` / `F-015 AC-2`。1 万件で p95 1 秒）に届かなかった
// 場合の代替を **段階 1〜4**（インデックス見直し → 非正規化テーブル → マテビュー → OpenSearch）
// として定めている。段階が上がるほど「検索の実装」は SQL から別のミドルウェアへ移るため、
// **その差し替えを 1 ファイルの書き換えで済ませられること**が前提条件になる。
// フリーワードの述語がアプリ各所に散っていると、その前提が最初から成立しない。
//
// ============================================================================
// 現在の実装: `ILIKE '%…%'`（索引は使わない。🔴 使えないことを実測した）
// ============================================================================
// Prisma の `contains` + `mode: 'insensitive'` は `column ILIKE '%…%'` に落ちる。これは
// `pg_trgm` の GIN（`gin_trgm_ops`）で加速できる**形**であり、`docs/03` §3.7.1 はそれを想定して
// いた。しかし **本プロダクトの RLS 構成では、その索引を使えない**（2026-09-07 実測。
// PostgreSQL 17 / `docs/03` §3.7.2 懸念 4 / migration `20260912000000_search_indexes`）:
//
//   `pg_catalog.textlike` / `texticlike` は **`proleakproof = false`** であり、PostgreSQL は
//   RLS が有効な表に対して leakproof でない条件をセキュリティ条件より下に降ろさない。
//   索引条件はセキュリティ条件より下で評価されるため、**`ILIKE` は索引条件になれず、
//   必ず Filter として後段に残る**。実際、`engineers` に `gin_trgm_ops` の索引を作っても
//   `app_tenant`（RLS 適用）からの計画は `Filter: display_name ~~* '%…%'` のままである
//   （RLS を素通りする superuser では同じ索引が使われる）。
//
// 🔴 したがって **trigram の GIN 索引は作らない**（使われない索引は書き込みコストだけを増やし、
//    「フリーワードは索引で速い」という事実と違う前提を残す）。代わりに効いているのは
//    **RLS の `tenant_id` 等値がそのまま索引条件になること**であり、フリーワードの走査は
//    常にそのテナントの行数に閉じる。`docs/03` §3.7.2 の最大テナント（3,000 件）で実測は
//    数十 ms であり、`F-009 AC-4` / `F-015 AC-2`（p95 1 秒）に十分な余裕がある。
// 🔴 **拡張の有無をコードで分岐しない。** 精度・速度が足りなくなったときの手順は
//    `docs/03` §3.7.3 の段階 1〜4 に従い、**このファイルを差し替える**。
//    根拠（leakproof と実行計画）は `tests/isolation/search-indexes.test.ts` ④ が常設で固定して
//    いるので、前提が変わればテストが落ちて判断をやり直せる。
//
// ============================================================================
// 既知の限界（🔴 情報境界の問題ではない）
// ============================================================================
// 1. `%` / `_` が LIKE のワイルドカードとして働く（利用者が入力した `%` は「任意の文字列」になる）。
// 2. 索引が効かない（上記）ため、テナントの行数に比例した走査になる。
// いずれも **母集団の外へは出ない** —— RLS（C3 / C4）が先に効き、述語は母集団の内側を絞るだけで
// ある。したがって `CLAUDE.md` §7 の「0 件」に数える種類の問題ではなく、精度と速度の問題である。
// 🔴 1 を「エスケープして完全な部分一致にする」ことは**本タスクでは行わない**。挙動を変えると
//    T-06-03 / T-06-04 の結合テストが固定した検索結果が変わるため、変更するなら `docs/02` の
//    `F-009` / `F-015` の受け入れ基準を先に改める（`CLAUDE.md` §8.7）。

/**
 * フリーワード 1 語ぶんの述語（Prisma の string filter）。
 *
 * 🔴 **`contains` + `mode: 'insensitive'` を書いてよいのはこのファイルだけ**である
 *    （`tests/static/search-sql-single-path.test.ts` が全ソースを AST で走査して固定する）。
 */
export type FreeWordFilter = { contains: string; mode: 'insensitive' };

/**
 * 🔴 フリーワード述語を組み立てる**唯一の関数**。
 *
 * 呼び出し側は「どの列を対象にするか」だけを決め、**照合の仕方には関与しない**
 * （関与させると、段階 2〜4 への差し替えが呼び出し側の数だけ必要になる）。
 */
export function freeWordFilter(term: string): FreeWordFilter {
  return { contains: term, mode: 'insensitive' };
}

/**
 * 複数列に対する OR（「氏名 **または** 希望条件に含む」）。
 *
 * 🔴 **対象列は呼び出し側が明示する。** 「テキスト列を全部見る」形にしない —— 画面が出さない PII
 *    （連絡先・現所属会社名）が検索対象に紛れ込むと、**一致・不一致から値を推測できる**
 *    （`docs/05` §6.4 #17 の決着）。
 * 🔴 列を増やすと**走査するデータ量がその分増える**（本ファイル冒頭のとおり索引は効かない）。
 *    増やしてよいのは「画面が出している値」だけである。
 */
export function freeWordOr<K extends string>(
  term: string,
  columns: readonly [K, ...K[]],
): { OR: { [P in K]?: FreeWordFilter }[] } {
  return {
    // 🔴 `as` は「計算されたキーを持つオブジェクトリテラル」を TypeScript が
    //    `{ [x: string]: … }` に広げるための最小の橋渡しである（`K` が保たれない）。
    //    型の緩和はこの 1 行に閉じており、返り値の型は呼び出し側で列名として固定される。
    OR: columns.map(
      (column) => ({ [column]: freeWordFilter(term) }) as { [P in K]?: FreeWordFilter },
    ),
  };
}

// ============================================================================
// ✅ 複数語の AND（2026-10-16。人間の明示指示「半角・全角スペース区切りで複数語 → AND 条件」）
// ============================================================================
/**
 * 🔴 **区切りは「空白」全般である**（半角 / 全角 / タブ / 改行）。全角空白（U+3000）を
 *    忘れると、日本語入力のまま打った利用者だけ 1 語扱いになる（最も起きる取りこぼし）。
 * 🔴 `\s` は全角空白を含まないので**明示する**（JavaScript の `\s` は U+3000 を含むが、
 *    実装依存に見える形を残さない）。
 */
const FREE_WORD_SEPARATOR = /[\s\u3000]+/u;

/**
 * 入力を語に割る。
 *
 * 🔴 **空語を落とす**（連続した空白・前後の空白で空文字が生まれる）。空文字の `contains` は
 *    **全件に一致する**ので、1 つ混ざると絞り込みが黙って無効になる。
 * 🔴 **語の順序を保つ**（述語の形が入力で決まることをテストで固定できる）。
 * 🔴 **重複を畳む** —— 同じ語を 2 回書いても述語が増えるだけで結果は変わらず、走査量が増える
 *    （索引が効かない検索である。ファイル冒頭の 🔴）。
 */
export function freeWordTerms(input: string): readonly string[] {
  const seen = new Set<string>();
  const terms: string[] = [];
  for (const raw of input.split(FREE_WORD_SEPARATOR)) {
    const term = raw.trim();
    if (term === '' || seen.has(term)) continue;
    seen.add(term);
    terms.push(term);
  }
  return terms;
}

/**
 * 🔴 **複数語 × 複数列**の述語（語は `AND`、列は `OR`）。
 *
 *   `Java 東京` → 「（案件名 or 記載）に `Java` を含み」**かつ**「（案件名 or 記載）に `東京` を含む」
 *
 * 🔴 **語をまたいで同じ列であることを要求しない** —— `Java` が案件名に、`東京` が記載に在る
 *    案件は一致する。1 列に両方を要求すると、入力した語の置かれ方を利用者が当てる必要が出る。
 * 🔴 **語が 0 個なら `null` を返す**（`{ AND: [] }` を返すと「条件が在るのに全件」になり、
 *    呼び出し側が「絞り込みが効いている」と誤って扱う）。
 * 🔴 1 語のときも `AND` の配列 1 本で返す（語数で述語の形を変えない = 結合テストが形で固定できる）。
 */
export function freeWordAllOf<K extends string>(
  input: string,
  columns: readonly [K, ...K[]],
): { AND: { OR: { [P in K]?: FreeWordFilter }[] }[] } | null {
  const terms = freeWordTerms(input);
  if (terms.length === 0) return null;
  return { AND: terms.map((term) => freeWordOr(term, columns)) };
}
