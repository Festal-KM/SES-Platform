// packages/db/src/search/plan.ts
// 検索の「計画」の共通形（SP-06 T-06-05 / docs/05 TBD-8）。
//
// ============================================================================
// 🔴 なぜ「母集団 + バケット列」という形なのか
// ============================================================================
// Phase 1 の並びは **①検索条件への適合 → ②更新日時 → ③id** である（`F-009 AC-1` /
// `docs/02` `F-009` 処理②）。①は**列の値ではなく述語**なので、`ORDER BY` に載せるには
// `CASE` 式（＝ raw SQL）が要る。それは「検索の実装を `packages/db/src/search/**` の 1 箇所に
// 閉じる」（T-06-05）と衝突するため採らない。代わりに **①で母集団を分割し、分割の順に読む**。
//
// - `where`   … 母集団そのもの。🔴 **一覧と `COUNT` はこの 1 つの値を共有する**（docs/05 §4.8）。
// - `buckets` … `where` を①で分割したもの。**先頭から順に読むと①の並びになる**。
//
// 🔴 **`buckets` は `where` を「過不足なく」分割する**（合併 = `where`、交わり = 空）。
//    したがって `COUNT(where)` は各バケットの件数の合計と必ず一致する
//    ＝ **並びの都合で `total` が変わらない**（docs/05 §4.8「一覧の件数」）。
// 🔴 **「分割するかどうか」の判定はプランを組み立てる関数だけが行う**（＝ `buckets.length`）。
//    読み出し側（`apps/web` の一覧）に `if (fit === null)` を書かせない —— 判定が 2 本になると、
//    「述語は分割したのに読み出しは分割していない」というずれが静かに入りうる
//    （T-06-04 のレビュー申し送り 2）。
//
// ============================================================================
// 🔴 SP-08（匿名候補の混在）との合成のしかた
// ============================================================================
// `docs/03` §3.7.1 / `program-design` 申し送り 18 は、匿名候補を **「自社スコープ」「共有スコープ」の
// 2 本のクエリに分け、アプリ層で決定的な順序でマージする**と定めている（1 本の SQL にまとめると
// 越境の実装が 1 箇所に集まらないため）。本形はそれと**直交する 2 軸**として合成できる:
//
//   第 1 軸（本ファイル）: `buckets`     … 適合による分割。**バケットの順序が第 1 キー**
//   第 2 軸（SP-08）:      スコープ      … 自社 / 共有。**同じバケット内で `ORDER BY` キーによる
//                                          k-way マージ**（`ENGINEER_LIST_ORDER_BY` が比較子の出所）
//
// つまり SP-08 は「各バケットについて 2 本のクエリを走らせ、`ENGINEER_LIST_ORDER_BY` で
// マージする」だけで済み、**本タスクの `buckets` の意味を変えずに載る**。
// 🔴 逆に「スコープをバケットとして並べる」（自社を全部出してから共有を出す）形にしてはならない
//    —— 自社と共有の境目が並びに現れ、**匿名候補の件数が並び順から読める**（docs/05 §4.8）。

/**
 * 検索の計画。
 *
 * @typeParam TWhere 述語の型（テーブルごとに列名を型で固定する。`Record<string, unknown>` にしない）
 */
export type SearchPlan<TWhere> = {
  /** 母集団（検索条件そのもの）。🔴 一覧と `COUNT` はこの値を共有する。 */
  readonly where: TWhere;
  /**
   * 🔴 母集団を並びの第 1 キーで分割したもの。**先頭から順に読む。**
   *    要素数 1 なら分割が無い（＝ 適合の差が生じない）ことを意味する。
   */
  readonly buckets: readonly [TWhere, ...TWhere[]];
};

/**
 * ソフト条件 1 つ分。`match`（適合）と `miss`（不適合）を**両方**明示的に持つ。
 *
 * 🔴 **`miss` を `NOT: match` で作らない。** SQL の三値論理では `NOT (available_from <= X)` は
 *    `available_from IS NULL` の行に対して NULL（＝ 偽）になり、**その行がどちらのバケットにも
 *    入らない ＝ 一覧から消える**。Prisma の `NOT` が nullable 列をどう展開するかはバージョン
 *    依存でもある。`match` と `miss` が**母集団を過不足なく 2 分する**ことは実装で保証し、
 *    `tests/isolation/engineers.test.ts` が「チェックボックスがオフなら 1 件も消えない」で固定する。
 */
export type SoftCondition<TWhere> = {
  readonly match: TWhere;
  readonly miss: TWhere;
};
