// packages/ui/src/lib/link-classes.ts
// 画面内の副次的な導線（一覧へ戻る / 次のページ / 条件を外す / キャンセル）の見た目。
// SP-21 T-21-04 で `globals.css` の `.ses-secondary-link` から移した。
//
// ============================================================================
// 🔴 なぜコンポーネントではなく**クラス定数**なのか
// ============================================================================
// `.ses-secondary-link` は移行前の実測で **39 箇所 / 17 ファイル**にあり、その内訳は
// `next/link` の `<Link>` / 素の `<a>` / `<button type="button">` の 3 種類である
// （T-21-03 が「一部だけ移すと片方だけ直る状態を作る」として一括で T-21-04 に残した）。
//
//   - `<Link>` を包むコンポーネントを `packages/ui` に置くと、**UI パッケージが
//     `next/link` に依存する**（`CLAUDE.md` §2.1 の依存方向はフレームワーク依存を
//     `apps/*` 側に閉じている）。
//   - `<a>` 用と `<Link>` 用に 2 つ作れば、**「同じ見た目のローカル実装を 2 つ作らない」**
//     （SP-21 T-21-02 ①）に自分から反する。
//
// したがって**見た目だけを定数**にし、要素の選択は呼び出し側に残す。
//
// ============================================================================
// 🔴 なぜ「間隔あり」と「間隔なし」で定数を 2 つに分けるのか
// ============================================================================
// 旧 `.ses-secondary-link` は `margin-top: 1rem` を**規則の中に内包**していた。移行時に
// その `mt-4` を基底へそのまま持ち込んだところ、**横並びの操作行 11 箇所で誤って効いた**:
//
//   - `flex items-center` の行（`S-007` / `S-012` の 保存＋キャンセル、`S-013` の取り消し、
//     検索の 送信＋条件を解除）で、隣の `Button` に対してリンクの中心が **8px 下にずれる**
//   - `<nav className="mt-4 flex …">` の中では、器とリンクの両方に `mt-4` が乗って
//     **上余白が 32px に二重化**する
//
// 🔴 そして `className="mt-0"` では直せない —— `cn()` は `tailwind-merge` ではなく、
//    `.mt-0` と `.mt-4` のどちらが勝つかは**生成 CSS の順**に委ねられる（`./cn.ts` の規律 2。
//    `components/field.tsx` 冒頭の「間隔は置かれる文脈が決める。基底に入れると `cn()` では
//    打ち消せない」と同じ話である）。**打ち消せない値を基底に入れない。**
//
// | `.ses-secondary-link` の宣言 | Tailwind | 置き場所 |
// |---|---|---|
// | `display: inline-block` | `inline-block` | 両方の定数（見た目そのもの） |
// | `font-size: 0.875rem` | `text-sm` | 同上 |
// | `color: var(--ses-muted)`（`#6b7280`） | `text-slate-500`（`#64748b`） | 同上。`--ses-muted` は T-21-07 で消える変数であり、パレットを slate（`Button` / `Input` と同系統）に統一する |
// | 🔴 `margin-top: 1rem` | `mt-4` | **`SECONDARY_LINK_STACKED_CLASSES` だけ**が持つ |

/**
 * 副次的な導線の見た目（**間隔を持たない**）。
 *
 * 🔴 **横に並べる文脈ではこちらを使う** —— `flex items-center` の操作行、`gap-*` を持つ
 *    ナビゲーション、文中に置くリンク。間隔は器（`gap-*` / `mb-*`）が決める。
 */
export const SECONDARY_LINK_CLASSES = 'inline-block text-sm text-slate-500';

/**
 * 縦に積む文脈用（`SECONDARY_LINK_CLASSES` + 上マージン）。旧 `.ses-secondary-link` と同値。
 *
 * 🔴 **直前の要素との間隔がここにしか無い場所でだけ使う** —— フォームの送信ボタンの下に
 *    置く「サインインへ戻る」など。器が `gap-*` を持つなら `SECONDARY_LINK_CLASSES` を使う
 *    （両方あると間隔が二重になる）。
 */
export const SECONDARY_LINK_STACKED_CLASSES = `mt-4 ${SECONDARY_LINK_CLASSES}`;
