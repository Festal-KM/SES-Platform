// 🔴 **「カードの面」を 1 箇所に持つ**（`docs/04` §7.9 の ③ component 層 / §7.2）。
//    SP-22（2026-10-02 の人間のブリーフ: 複数人が別の画面を担当しても 1 つの SaaS に見える共通フレーム）。
//
// ============================================================================
// なぜ定数を 1 本切るのか
// ============================================================================
// ブリーフが要求するホーム画面は **KPI カード 4 枚 / セクションのカード / 右レールのカード**で
// 構成される。これを部品ごとに `rounded-md border border-border bg-surface` と書き写すと、
// **「カードの面」が 5 箇所に分かれる** —— そのうち 1 つだけ radius が 8px になる、1 つだけ
// 影が付く、1 つだけ枠線が濃い、という状態が必ず生まれる（`docs/04` §7.9 が記録している
// 「色が TSX 直書きで 1,038 箇所」と同じ拡散の始まり方である）。
//
// 🔴 **`Card`（shadcn/ui 由来）もここから取る。** 2 本になった瞬間に「どちらが正か」の判断が
//    画面ごとに発生する（`lib/cn.ts` の規律 3 と同じ構え）。
//
// ============================================================================
// 🔴 この面が持たないもの
// ============================================================================
// - **影**（§7.9）。🔴 階層は border と background の差で表す。影が許されるのは overlay と
//   入力欄の輪郭の 2 箇所だけであり（`lib/overlay-classes.ts` / `lib/control-classes.ts`）、
//   **カードを浮かせるための影を持たない。**
// - **hover / active**。カードは「押す対象」ではない（押せるのは中の導線である）。面が
//   ポインタで動くと、どこが操作可能かの手がかりが薄れる（§7.10 の hover の 🔴）。
// - **内側の余白**。置かれる文脈が決める（`lib/link-classes.ts` の「打ち消せない値を基底に
//   入れない」と同じ理由）。各部品が §7.9 の 7 段から選ぶ。
import { cn } from './cn.js';

/**
 * カード / パネルの面（`Card` / `KpiCard` / `RailCard` / `Timeline` / `RankedList`）。
 *
 * 🔴 **地は `--color-surface`**（ページの地 `--color-bg` とは役割が違う。値は同じ白だが、
 *    ページ地を淡いグレーに変える判断が入ったときに**カード側が動かない**ことが要点である。
 *    `apps/web/app/tailwind.css` の `--color-surface` の 🔴）。
 * 🔴 **radius は 6px（`rounded-md`）**（§7.9 の 2 段のうちパネルの段）。
 * 🔴 **枠線は 1px の `--color-border`**（§7.9 の border は 1px。強調が要る箇所のみ左端 2px）。
 */
export const CARD_SURFACE_CLASSES = cn('rounded-md border border-border bg-surface');

/**
 * カードの内側の余白（§7.9 の `--space-4` = 16px。「カードの内側」の段そのもの）。
 *
 * 🔴 **段を部品ごとに選び直さない。** ホームのカードが 16px、右レールのカードが 20px という
 *    状態になると、横に並んだときに中身の開始位置が揃わない（§7.1 の密度の話）。
 */
export const CARD_PADDING_CLASSES = 'p-4';
